"""Re-creates the neutral Stage HMI fixture tests/Fixtures/PtcXaeMcpHmiFixture (issue #163).

Expands the TE2000 "TwinCAT HMI Project" starter template that the HMI engineering
installs (StarterPrj_PackagesConfig) the way the XAE's "Add New Project" would, but
without Visual Studio: the .vstemplate is read for the file mapping, and every
placeholder TcHmiWizardGeneral.TcHmiWizGeneral.RunStarted fills in is substituted here:

  $safeprojectname$                         project name
  $safeprojectname2$                        PrepareProjectPhysicalName_Framework(name)
  $guid1$                                   ProjectGuid - derived from the name (uuid5),
                                            so a re-run gives byte-identical output
  $Configuration_RelativePath_To_Packages$  "..\\" (the project sits in a solution folder)
  $<package>_VERSION$                       newest version of that package in the local
                                            Beckhoff NuGet feed (--feed)
  $relativedestinationdirectory$            relative path from the .theme file to the
                                            restored HMI framework (same form the XAE writes)

A neutral .sln next to the project folder is written as well; HmiFixture reuses it.

Nothing needs the XAE, the MCP server or a network. No packages/, no build or server
output and no machine paths are written - the XAE restores packages/ from the local
Beckhoff feed when the (TEMP copy of the) fixture is opened.

Requirements: Windows with the TE2000 HMI engineering installed, Python 3.11+.

Usage:
  python tests/Fixtures/create_hmi_fixture.py [--out <dir>] [--force]
         [--template <StarterPrj_PackagesConfig dir>] [--feed <nupkg dir>]

The integration suite never opens this copy directly: Stage HMI copies it to %TEMP%
per run (src/PtcXaeMcp.IntegrationTests/HmiFixture.cs, HmiFixtureSource.cs). Keep the
names below in sync with HmiFixtureSource.cs.
"""
import argparse
import os
import re
import shutil
import sys
import uuid
import xml.etree.ElementTree as ET

NAME = "PtcXaeMcpHmiFixture"      # fixture folder + .sln name
PROJECT = "PtcXaeMcpHmi"           # HMI project name (.hmiproj, HmiTitle)

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_OUT = os.path.join(HERE, NAME)
DEFAULT_TEMPLATE = (r"C:\Program Files (x86)\Beckhoff\TwinCAT\Functions\TE2000-HMI-Engineering"
                    r"\Templates\ProjectTemplates\TcXaeShell\StarterPrj_PackagesConfig")
DEFAULT_FEED = r"C:\ProgramData\Beckhoff\NuGetPackages"

VSTEMPLATE_NS = {"vs": "http://schemas.microsoft.com/developer/vstemplate/2005"}
HMI_PROJECT_TYPE_GUID = "{FE7A1B72-C5B7-4D7C-BB7D-76384D4DE8E1}"
# Fixed namespace so the GUIDs depend on the names only (never on time or machine).
GUID_NAMESPACE = uuid.UUID("6f1c2a52-3b0e-4f43-9a51-163000000163")

PACKAGES = [
    "Beckhoff.TwinCAT.HMI.Framework",
    "Beckhoff.TwinCAT.HMI.Functions",
    "Beckhoff.TwinCAT.HMI.Controls",
    "Beckhoff.TwinCAT.HMI.Server.Engineering",
    "Microsoft.TypeScript.MSBuild",
]
FRAMEWORK_RUNTIME = "runtimes/native1.12-tchmi"

# A Visual-Studio-style template placeholder ($name$); MSBuild's $(…) never matches.
PLACEHOLDER = re.compile(r"\$[A-Za-z_][A-Za-z0-9_.]*\$")

# Template slips fixed the way the XAE's own config resync leaves them: the template's
# tchmiconfig.json names Themes/Base-Dark/Base.theme, but the file it ships is Base-Dark.theme.
# The template's Desktop.view shows the Beckhoff company logo; the fixture shows a neutral
# placeholder instead (LOGO_SVG below) - the Beckhoff logo is a trademark of Beckhoff Automation
# and is not redistributed with this repository (THIRD-PARTY-NOTICES.md).
TEMPLATE_LOGO = "Images/Beckhoff_Logo.svg"
FIXTURE_LOGO = "Images/Fixture_Logo.svg"
POST_FIXES = {
    "Properties/tchmiconfig.json": [("Themes/Base-Dark/Base.theme", "Themes/Base-Dark/Base-Dark.theme")],
    "Desktop.view": [("ViewDesktopBeckhoffLogo", "ViewDesktopLogo"), (TEMPLATE_LOGO, FIXTURE_LOGO)],
    f"{PROJECT}.hmiproj": [(TEMPLATE_LOGO.replace("/", "\\"), FIXTURE_LOGO.replace("/", "\\"))],
}

# Same box the template logo occupies (219 x 66 user units, 194 x 57 px in Desktop.view).
LOGO_SVG = """<?xml version="1.0" encoding="UTF-8"?>
<svg width="219.4" height="65.854" version="1.1" viewBox="0 0 219.4 65.854" xmlns="http://www.w3.org/2000/svg">
  <rect x="1" y="1" width="217.4" height="63.854" rx="6" fill="none" stroke="#7a7a7a" stroke-width="2"/>
  <text x="109.7" y="40" font-family="Roboto Condensed, Arial, sans-serif" font-size="22" text-anchor="middle" fill="#7a7a7a">HMI fixture</text>
</svg>
"""

FIXTURE_GITIGNORE = """# Generated by the XAE / HMI engineering on open, build and server start - sources only.
packages/
Packages/
.vs/
.engineering_servers/
bin/
obj/
*.user
*.suo
# The HMI server writes its full config (incl. a generated certificate and private key) on first start.
PtcXaeMcpHmi/Server/**/*.json
"""


def stable_guid(label: str) -> str:
    return "{" + str(uuid.uuid5(GUID_NAMESPACE, label)).upper() + "}"


def physical_name(s: str) -> str:
    """TcHmiWizardBase.PrepareProjectPhysicalName_Framework."""
    for k, v in {"ä": "a", "ö": "o", "ü": "u", "Ä": "A", "Ö": "O", "Ü": "U", "ß": "sz", "@": "at"}.items():
        s = s.replace(k, v)
    s = s.replace(" ", "_").replace(".", "_")
    return re.sub(r"[^\x00-\x7F]+", "", s)


def version_key(v: str):
    return tuple(int(p) if p.isdigit() else -1 for p in v.split("."))


def latest_versions(feed: str) -> dict:
    """Newest <id>.<version>.nupkg per package id (TcHmiNuGetUtils.QueryLocalAvailableNuGetVersions)."""
    found = {p: [] for p in PACKAGES}
    for f in os.listdir(feed):
        if not f.lower().endswith(".nupkg"):
            continue
        stem = f[:-len(".nupkg")]
        for p in PACKAGES:
            rest = stem[len(p) + 1:]
            if stem.lower().startswith(p.lower() + ".") and re.fullmatch(r"\d+(\.\d+)+", rest):
                found[p].append(rest)
    missing = [p for p, v in found.items() if not v]
    if missing:
        raise SystemExit(f"No local NuGet package for {', '.join(missing)} in {feed}.")
    return {p: max(v, key=version_key) for p, v in found.items()}


def relative_framework_dir(target_rel: str, framework_version: str) -> str:
    """$relativedestinationdirectory$ for a file at target_rel (project-relative).

    Same shape the XAE writes (TcHmiHelper.GetReplacementForRelativeDestinationDir), e.g.
    ./../../../Packages/Beckhoff.TwinCAT.HMI.Framework.<v>/runtimes/native1.12-tchmi
    for Themes/Base/Base.theme - packages/ sits next to the project folder.
    """
    depth = len(target_rel.replace("\\", "/").split("/"))  # dirs below the project + 1 for the project
    return ("./" + "../" * depth + f"Packages/Beckhoff.TwinCAT.HMI.Framework.{framework_version}/"
            + FRAMEWORK_RUNTIME)


def expand_text(data: bytes, replacements: dict, target_rel: str) -> bytes:
    bom = data.startswith(b"\xef\xbb\xbf")
    text = data[3:].decode("utf-8") if bom else data.decode("utf-8")
    for k, v in replacements.items():
        text = text.replace(k, v)
    if "$relativedestinationdirectory$" in text:
        text = text.replace("$relativedestinationdirectory$",
                            relative_framework_dir(target_rel, replacements["$Beckhoff.TwinCAT.HMI.Framework_VERSION$"]))
    for old, new in POST_FIXES.get(target_rel.replace("\\", "/"), []):
        text = text.replace(old, new)
    left = sorted(set(PLACEHOLDER.findall(text)))
    if left:
        raise SystemExit(f"Unsubstituted placeholder(s) {left} in {target_rel}.")
    return (b"\xef\xbb\xbf" if bom else b"") + text.encode("utf-8")


def solution_text(project: str, rel_path: str, project_guid: str, solution_guid: str) -> str:
    lines = [
        "",
        "Microsoft Visual Studio Solution File, Format Version 12.00",
        "# TcXaeShell Solution File, Format Version 11.00",
        "VisualStudioVersion = 17.10.35827.194",
        "MinimumVisualStudioVersion = 10.0.40219.1",
        f'Project("{HMI_PROJECT_TYPE_GUID}") = "{project}", "{rel_path}", "{project_guid}"',
        "EndProject",
        "Global",
        "\tGlobalSection(SolutionConfigurationPlatforms) = preSolution",
        "\t\tDebug|TwinCAT HMI = Debug|TwinCAT HMI",
        "\t\tRelease|TwinCAT HMI = Release|TwinCAT HMI",
        "\tEndGlobalSection",
        "\tGlobalSection(ProjectConfigurationPlatforms) = postSolution",
        f"\t\t{project_guid}.Debug|TwinCAT HMI.ActiveCfg = Debug|TwinCAT HMI",
        f"\t\t{project_guid}.Debug|TwinCAT HMI.Build.0 = Debug|TwinCAT HMI",
        f"\t\t{project_guid}.Release|TwinCAT HMI.ActiveCfg = Release|TwinCAT HMI",
        f"\t\t{project_guid}.Release|TwinCAT HMI.Build.0 = Release|TwinCAT HMI",
        "\tEndGlobalSection",
        "\tGlobalSection(SolutionProperties) = preSolution",
        "\t\tHideSolutionNode = FALSE",
        "\tEndGlobalSection",
        "\tGlobalSection(ExtensibilityGlobals) = postSolution",
        f"\t\tSolutionGuid = {solution_guid}",
        "\tEndGlobalSection",
        "EndGlobal",
        "",
    ]
    return "\r\n".join(lines)


def write_bytes(path: str, data: bytes):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(data)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", default=DEFAULT_OUT, help=f"fixture folder (default: {DEFAULT_OUT})")
    ap.add_argument("--force", action="store_true", help="delete --out first")
    ap.add_argument("--template", default=DEFAULT_TEMPLATE, help="StarterPrj_PackagesConfig template folder")
    ap.add_argument("--feed", default=DEFAULT_FEED, help="local Beckhoff NuGet feed (*.nupkg)")
    a = ap.parse_args()

    out = os.path.abspath(a.out)
    if os.path.exists(out):
        if not a.force:
            raise SystemExit(f"{out} exists - pass --force to recreate it.")
        shutil.rmtree(out)

    vstemplate = os.path.join(a.template, "StarterPrj.vstemplate")
    if not os.path.isfile(vstemplate):
        raise SystemExit(f"HMI project template not found: {vstemplate}")

    versions = latest_versions(a.feed)
    replacements = {
        "$safeprojectname$": PROJECT,
        "$safeprojectname2$": physical_name(PROJECT),
        "$guid1$": stable_guid(f"ptc-xae-mcp/{NAME}/{PROJECT}.hmiproj"),
        "$Configuration_RelativePath_To_Packages$": "..\\",
    }
    for p, v in versions.items():
        replacements[f"${p}_VERSION$"] = v

    root = ET.parse(vstemplate).getroot()
    project = root.find("vs:TemplateContent/vs:Project", VSTEMPLATE_NS)
    if project is None:
        raise SystemExit("No <Project> in the .vstemplate.")
    project_dir = os.path.join(out, PROJECT)

    def emit(source_name: str, target_rel: str, replace: bool):
        if target_rel.replace("\\", "/") == TEMPLATE_LOGO:
            # Neutral placeholder under the fixture's own name; Desktop.view and the .hmiproj are
            # pointed at it by POST_FIXES.
            write_bytes(os.path.join(project_dir, FIXTURE_LOGO), LOGO_SVG.encode("utf-8"))
            return
        with open(os.path.join(a.template, source_name), "rb") as f:
            data = f.read()
        if replace and data:
            data = expand_text(data, replacements, target_rel)
        write_bytes(os.path.join(project_dir, target_rel), data)

    project_file = project.get("TargetFileName").replace("$safeprojectname$", PROJECT)
    emit(project.get("File"), project_file, project.get("ReplaceParameters") == "true")

    count = 1
    for item in project.findall("vs:ProjectItem", VSTEMPLATE_NS):
        target = item.get("TargetFileName")
        # The template's Server\<Ext>\*.json are 0-byte placeholders. For a NEW project the engineering
        # deletes them before the first server start (TcHmiProjectNode.InitializeServer, isNewProject); an
        # opened existing project keeps them, and TcHmiSrv then fails with Error_Schema REQUIRED_FIELD
        # (PROJECTNAME) (live 2026-10-10). Without the files the server generates its own config.
        if target.replace("/", "\\").lower().startswith("server\\") and target.lower().endswith(".json"):
            continue
        emit(item.text.strip(), target, item.get("ReplaceParameters") == "true")
        count += 1
    # Empty template folders (Imports\Images, Server\TcHmiTextStorage, ...). Git does not keep
    # empty folders; the HMI engineering creates them on open.
    for folder in project.findall("vs:Folder", VSTEMPLATE_NS):
        os.makedirs(os.path.join(project_dir, folder.get("TargetFolderName")), exist_ok=True)

    sln = os.path.join(out, NAME + ".sln")
    write_bytes(sln, b"\xef\xbb\xbf" + solution_text(
        PROJECT, f"{PROJECT}\\{project_file}", replacements["$guid1$"],
        stable_guid(f"ptc-xae-mcp/{NAME}.sln")).encode("utf-8"))
    write_bytes(os.path.join(out, ".gitignore"), FIXTURE_GITIGNORE.encode("utf-8"))

    print(f"HMI fixture created: {sln}")
    print(f"  {count} project files, packages: " + ", ".join(f"{p} {v}" for p, v in versions.items()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
